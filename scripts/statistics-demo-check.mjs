import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { launchBrowser } from "./_browser.mjs";

const origin = process.env.VOLLEY_ORIGIN || "http://127.0.0.1:4173";
await mkdir("tmp/statistics-demo-check", { recursive: true });
const browser = await launchBrowser();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${origin}/record/?mode=statistics`);
  const scoreSentinel = JSON.stringify({ demoIsolationCheck: "existing scoring record" });
  await page.evaluate(saved => localStorage.setItem("volley-record-state-v1", saved), scoreSentinel);
  await page.screenshot({ path: "tmp/statistics-demo-check/setup.png", fullPage: true, animations: "disabled" });
  await page.locator("#load-statistics-demo").click();
  await page.locator(".statistics-table").waitFor();
  assert.equal(await page.locator('[data-act="ok"]').count(), 0);
  assert.equal(await page.locator(".statistics-table tbody tr").count(), 14);
  assert.match(await page.locator(".statistics-paper-meta").innerText(), /样例比赛/);
  assert.match(await page.locator(".statistics-paper-result").innerText(), /3 : 1/);
  assert.equal(await page.locator('[data-row-total="0-serve"]').innerText(), "14");
  await page.locator("#view-statistics-analysis").click();
  assert.equal(await page.locator(".statistics-analysis-modal .analysis-summary strong").first().innerText(), "66");
  assert.equal(await page.locator(".statistics-analysis-modal .analysis-player-table tbody tr").count(), 14);
  await page.locator("#close-statistics-analysis").click();
  const plus = page.locator('[data-row="0"][data-group="serve"][data-outcome="success"][data-delta="1"]');
  await plus.click();
  await page.reload();
  assert.equal(await page.locator('[data-row-total="0-serve"]').innerText(), "15");
  const before = await page.evaluate(() => localStorage.getItem("volley-record-statistics-v1"));
  await page.locator("#load-statistics-demo").click();
  await page.locator('[data-act="cancel"]').click();
  assert.equal(await page.evaluate(() => localStorage.getItem("volley-record-statistics-v1")), before);
  await page.locator("#load-statistics-demo").click();
  await page.locator('[data-act="ok"]').click();
  assert.equal(await page.locator('[data-row-total="0-serve"]').innerText(), "14");
  await page.locator("#edit-statistics").click();
  assert.equal(await page.locator("#stats-gender").inputValue(), "混合");
  assert.equal(await page.locator('[name="gender-2"]').inputValue(), "女");
  await page.locator('[name="competition"]').fill("我的真实比赛");
  await page.locator("#load-statistics-demo").click();
  await page.locator('[data-act="cancel"]').click();
  assert.equal(await page.locator('[name="competition"]').inputValue(), "我的真实比赛");
  await page.getByRole("button", { name: "保存并返回统计表" }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator("#load-statistics-demo").click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('[data-act="ok"]').click();
  assert.match(await page.locator(".statistics-paper-meta").innerText(), /样例比赛/);
  await page.locator("#reset-app").click();
  await page.locator('[data-act="ok"]').click();
  await page.locator("#statistics-form").waitFor();
  await page.screenshot({ path: "tmp/statistics-demo-check/mobile.png", fullPage: true, animations: "disabled" });
  await page.locator('[name="competition"]').fill("尚未开始的比赛草稿");
  const draft = await page.evaluate(() => localStorage.getItem("volley-record-statistics-v1"));
  await page.locator("#load-statistics-demo").click();
  await page.locator('[data-act="cancel"]').click();
  assert.equal(await page.evaluate(() => localStorage.getItem("volley-record-statistics-v1")), draft);
  await page.locator("#load-statistics-demo").click();
  await page.locator('[data-act="ok"]').click();
  await page.locator(".statistics-table").waitFor();
  assert.equal(await page.evaluate(() => localStorage.getItem("volley-record-state-v1")), scoreSentinel);
  assert.deepEqual(errors, []);
  console.log("Statistics sample passed: one-click empty setup, complete mixed roster/scores/counts/report, editing/reload, confirm/cancel protection in setup and table, mobile and scoring isolation.");
} finally { await browser.close(); }
