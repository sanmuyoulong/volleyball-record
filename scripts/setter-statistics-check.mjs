import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { launchBrowser } from "./_browser.mjs";
import { sampleStatistics } from "../src/statistics-state.js";

const origin = process.env.VOLLEY_ORIGIN || "http://127.0.0.1:4173";
await mkdir("tmp/setter-check", { recursive: true });
const browser = await launchBrowser();
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${origin}/record/?mode=statistics`);
  assert.equal(await page.locator("#enable-setter-statistics").isChecked(), false);
  assert.equal(await page.locator("#setter-roster-panel").isVisible(), false);
  await page.locator("#load-statistics-demo").click();
  await page.locator(".setter-table").waitFor();
  assert.equal(await page.locator(".setter-table tbody tr").count(), 4);
  assert.equal(await page.locator(".statistics-table tbody tr").count(), 14);
  assert.deepEqual(await page.locator(".setter-table thead tr:nth-child(2) th").allTextContents(), ["失误", "一般", "到位", "总数", "失误", "一般", "到位", "总数", "得分", "一般", "失误", "总数"]);
  const primary = await page.evaluate(() => JSON.stringify(JSON.parse(localStorage.getItem("volley-record-statistics-v1")).players));
  const button = (row, group, outcome, delta) => page.locator(`[data-setter-row="${row}"][data-group="${group}"][data-outcome="${outcome}"][data-delta="${delta}"]`);
  assert.equal(await button(2, "inSystem", "success", 1).isDisabled(), true);
  await button(0, "inSystem", "success", 1).click();
  await button(0, "secondAttack", "success", 1).click();
  assert.equal(await page.locator('[data-setter-row-total="0-inSystem"]').innerText(), "41");
  assert.equal(await page.locator('[data-setter-team-total="secondAttack-success"]').innerText(), "5");
  assert.equal(await page.evaluate(() => JSON.stringify(JSON.parse(localStorage.getItem("volley-record-statistics-v1")).players)), primary);
  await page.reload();
  assert.equal(await page.locator('[data-setter-row-total="0-inSystem"]').innerText(), "41");
  await page.locator("#view-statistics-analysis").click();
  assert.equal(await page.locator(".statistics-analysis-modal .analysis-print-page").count(), 4);
  assert.equal(await page.locator(".statistics-analysis-modal .analysis-summary strong").first().innerText(), "66");
  assert.equal(await page.locator(".statistics-analysis-modal .analysis-setters .analysis-summary strong").nth(2).innerText(), "5");
  await page.locator("#close-statistics-analysis").click();
  await page.locator("#edit-statistics").click();
  await page.locator("#enable-setter-statistics").uncheck();
  await page.getByRole("button", { name: "保存并返回统计表" }).click();
  assert.equal(await page.locator(".setter-table").count(), 0);
  assert.equal(await page.locator("#statistics-analysis-print .analysis-setters").count(), 0);
  await page.locator("#edit-statistics").click();
  await page.locator("#enable-setter-statistics").check();
  assert.equal(await page.locator('[name="setter-name-0"]').inputValue(), "程野");
  assert.equal(await page.locator('[data-setter-pick="0"]').isDisabled(), true);
  await page.locator('[name="setter-name-0"]').fill("");
  assert.equal(await page.locator('[name="setter-number-0"]').getAttribute("readonly"), "");
  await page.getByRole("button", { name: "保存并返回统计表" }).click();
  assert.match(await page.locator("#validation-slot").innerText(), /不能清空/);
  await page.locator('[name="setter-name-0"]').fill("程野");
  await page.locator('[data-setter-pick="2"]').selectOption("2");
  assert.equal(await page.locator('[name="setter-name-2"]').inputValue(), "陈放");
  assert.equal(await page.locator('[name="setter-gender-2"]').inputValue(), "女");
  await page.locator('[name="setter-name-3"]').fill("独立二传");
  await page.locator('[name="setter-number-3"]').fill("99");
  await page.locator('[name="setter-gender-3"]').selectOption("女");
  assert.equal(await page.locator('[name^="setter-name-"]').count(), 4);
  await page.locator(".setter-setup-section").screenshot({ path: "tmp/setter-check/setup.png", animations: "disabled" });
  await page.getByRole("button", { name: "保存并返回统计表" }).click();
  assert.equal(await page.locator('[data-setter-row-total="0-inSystem"]').innerText(), "41");
  assert.equal(await button(2, "inSystem", "error", -1).isDisabled(), true);
  for (const group of ["inSystem", "outOfSystem", "secondAttack"]) {
    for (const outcome of ["success", "normal", "error"]) await button(2, group, outcome, 1).click();
    assert.equal(await page.locator(`[data-setter-row-total="2-${group}"]`).innerText(), "3");
    await button(2, group, "error", -1).click();
  }
  await page.locator("#data-manager").click();
  const pendingDownload = page.waitForEvent("download");
  await page.locator("#export-statistics").click();
  const backupPath = resolve("tmp/setter-check/backup.json");
  await (await pendingDownload).saveAs(backupPath);
  const saved = JSON.parse(await readFile(backupPath, "utf8"));
  assert.equal(saved.data.setterStatistics.players[0].counts.inSystem.success, 32);
  await page.locator("#close-statistics-data").click();
  await button(0, "inSystem", "success", 1).click();
  await page.locator("#data-manager").click();
  await page.locator("#import-statistics").setInputFiles(backupPath);
  await page.locator('[data-act="ok"]').click();
  assert.equal(await page.locator('[data-setter-row-total="0-inSystem"]').innerText(), "41");
  await page.locator(".setter-live-section").screenshot({ path: "tmp/setter-check/table.png", animations: "disabled" });
  await page.pdf({ path: "tmp/setter-check/setter-analysis.pdf", preferCSSPageSize: true, printBackground: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator(".setter-sheet-scroll").evaluate(node => node.scrollLeft = node.scrollWidth);
  await button(0, "secondAttack", "normal", 1).click();
  assert.equal(await page.locator('[data-setter-row-total="0-secondAttack"]').innerText(), "8");
  await page.locator("#view-statistics-analysis").click();
  assert.equal(await page.locator(".statistics-analysis-modal .analysis-setter-player-table tbody tr").count(), 12);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: "tmp/setter-check/mobile-report.png", fullPage: true, animations: "disabled" });
  await page.locator("#close-statistics-analysis").click();
  await page.pdf({ path: "tmp/setter-check/setter-mobile.pdf", preferCSSPageSize: true, printBackground: true });
  assert.deepEqual(errors, []);
  await context.close();

  const legacy = sampleStatistics();
  delete legacy.setterStatistics;
  const legacyContext = await browser.newContext();
  await legacyContext.addInitScript(saved => localStorage.setItem("volley-record-statistics-v1", JSON.stringify(saved)), legacy);
  const legacyPage = await legacyContext.newPage();
  await legacyPage.goto(`${origin}/record/?mode=statistics`);
  assert.equal(await legacyPage.locator(".setter-table").count(), 0);
  await legacyPage.locator("#edit-statistics").click();
  await legacyPage.locator("#enable-setter-statistics").check();
  await legacyPage.getByRole("button", { name: "保存并返回统计表" }).click();
  assert.match(await legacyPage.locator("#validation-slot").innerText(), /至少填写/);
  await legacyContext.close();
  console.log("Setter statistics passed: opt-in and old data, four independent/set-from-roster players, three ordered groups, +/- and totals, no double counting, disable/re-enable, backup restore, specialized report, desktop/mobile PDF and scrolling.");
} finally { await browser.close(); }
