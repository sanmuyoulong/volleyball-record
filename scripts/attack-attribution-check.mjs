import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { launchBrowser } from "./_browser.mjs";
import { buildAttackComparison } from "../src/attack-attribution.js";

const origin = process.env.VOLLEY_ORIGIN || "http://127.0.0.1:4173";
await mkdir("tmp/attack-attribution-check", { recursive: true });
const browser = await launchBrowser();
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const state = () => page.evaluate(() => JSON.parse(localStorage.getItem("volley-record-statistics-v1")));
  const button = (outcome, delta) => page.locator(`[data-row="2"][data-group="attack"][data-outcome="${outcome}"][data-delta="${delta}"]`);
  await page.goto(`${origin}/record/?mode=statistics`);
  await page.locator("#load-statistics-demo").click();
  assert.equal(await page.locator("#active-setter").inputValue(), "0");
  const baseline = await state();
  const initial = buildAttackComparison(baseline);
  await page.evaluate(() => window.originalStatisticsTable = document.querySelector(".statistics-table"));
  await button("success", 1).click();
  await page.locator("#active-setter").selectOption("1");
  await button("success", 1).click();
  await button("error", 1).click();
  await page.locator("#active-setter").selectOption("0");
  await button("success", -1).click();
  assert.match(await page.locator("#statistics-last-action").innerText(), /撤回归属：2 号 陆骁/);
  let saved = await state();
  let report = buildAttackComparison(saved);
  assert.equal(saved.players[2].counts.attack.success, baseline.players[2].counts.attack.success + 1);
  assert.equal(report.groups[0].success, initial.groups[0].success + 1);
  assert.equal(report.groups[1].success, initial.groups[1].success);
  assert.equal(report.groups[1].error, initial.groups[1].error + 1);
  assert.equal(await page.evaluate(() => window.originalStatisticsTable === document.querySelector(".statistics-table")), true);
  await page.locator("#active-setter-details summary").click();
  assert.equal(await page.locator("#active-setter-players tbody tr").count(), 13);
  await page.locator("#active-setter").selectOption("1");
  await page.reload();
  assert.equal(await page.locator("#active-setter").inputValue(), "1");
  await page.locator("#active-setter").selectOption("");
  await button("normal", 1).click();
  assert.equal(buildAttackComparison(await state()).unassigned.normal, 1);

  await page.locator("#edit-statistics").click();
  assert.equal(await page.locator('[name="setter-number-0"]').getAttribute("readonly"), "");
  await page.locator('[data-setter-pick="2"]').selectOption("8");
  await page.locator('[name="setter-name-3"]').fill("独立二传");
  await page.locator('[name="setter-number-3"]').fill("99");
  await page.locator('[name="setter-gender-3"]').selectOption("女");
  await page.getByRole("button", { name: "保存并返回统计表" }).click();
  assert.equal(await page.locator("#active-setter option").count(), 5);
  await page.locator("#active-setter").selectOption("3");
  await button("error", 1).click();
  await page.locator("#view-statistics-analysis").click();
  assert.equal(await page.locator(".statistics-analysis-modal .analysis-print-page").count(), 4);
  assert.equal(await page.locator(".statistics-analysis-modal .attack-comparison-summary tbody tr").count(), 5);
  assert.equal(await page.locator(".statistics-analysis-modal .attack-comparison-players tbody tr").count(), 14);
  assert.equal(await page.locator('.statistics-analysis-modal [data-comparison-setter="3"] td').nth(4).innerText(), "-100.0%");
  await page.locator(".statistics-analysis-modal .analysis-attack-comparison").screenshot({ path: "tmp/attack-attribution-check/comparison-desktop.png", animations: "disabled" });
  await page.locator("#close-statistics-analysis").click();

  await page.locator("#data-manager").click();
  const pendingDownload = page.waitForEvent("download");
  await page.locator("#export-statistics").click();
  const backup = resolve("tmp/attack-attribution-check/backup.json");
  await (await pendingDownload).saveAs(backup);
  const exported = JSON.parse(await readFile(backup, "utf8"));
  await page.locator("#close-statistics-data").click();
  await button("error", 1).click();
  await page.locator("#data-manager").click();
  await page.locator("#import-statistics").setInputFiles(backup);
  await page.locator('[data-act="ok"]').click();
  assert.deepEqual((await state()).attackAttribution, exported.data.attackAttribution);
  await page.locator("#active-setter-details summary").click();
  await page.locator(".active-setter-panel").screenshot({ path: "tmp/attack-attribution-check/active-desktop.png", animations: "disabled" });
  await page.pdf({ path: "tmp/attack-attribution-check/comparison-desktop.pdf", preferCSSPageSize: true, printBackground: true });
  await page.emulateMedia({ media: "print" });
  const sizes = await page.locator("#statistics-analysis-print .analysis-print-page").evaluateAll(nodes => nodes.map(n => ({ width: n.scrollWidth, height: n.scrollHeight })));
  assert.equal(sizes.length, 4);
  assert.ok(sizes.every(s => s.height < 755), JSON.stringify(sizes));
  console.log("Print page dimensions:", sizes);
  await page.emulateMedia({ media: "screen" });

  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator("#active-setter").selectOption("0");
  assert.equal(await page.locator("#active-setter-details").getAttribute("open"), "");
  await page.locator(".active-setter-panel").screenshot({ path: "tmp/attack-attribution-check/active-mobile.png", animations: "disabled" });
  await page.locator("#view-statistics-analysis").click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator("#close-statistics-analysis").click();
  await page.emulateMedia({ media: "print" });
  await page.pdf({ path: "tmp/attack-attribution-check/comparison-mobile.pdf", preferCSSPageSize: true, printBackground: true });
  assert.deepEqual(errors, []);
  await context.close();
  console.log("Attack attribution passed: setter switching, reverse correction, cumulative totals, unassigned attacks, same-player comparison, independent setter, backup restore, four setters / fourteen attackers, desktop and mobile PDF.");
} finally { await browser.close(); }
